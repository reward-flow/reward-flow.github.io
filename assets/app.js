"use strict";

(() => {
  const data = window.REWARDFLOW_DATA;
  const config = window.REWARDFLOW_CONFIG || {};
  const $ = (selector, root = document) => root.querySelector(selector);
  const $$ = (selector, root = document) => Array.from(root.querySelectorAll(selector));

  // Link configuration is intentionally separate from the visual implementation.
  if (config.paperUrl) $$("[data-paper-link]").forEach(a => a.href = config.paperUrl);
  if (config.codeUrl) {
    const link = $("#code-link");
    link.href = config.codeUrl;
    link.target = "_blank";
    link.rel = "noopener";
    $(".button-detail", link).remove();
    $("#code-status").textContent = "Research code is available on GitHub.";
  }
  if (config.arxivUrl) {
    const link = document.createElement("a");
    link.className = "button button-secondary";
    link.href = config.arxivUrl;
    link.target = "_blank";
    link.rel = "noopener";
    link.textContent = "arXiv ↗";
    $(".hero-actions").append(link);
  }

  // Native dialog supplies focus trapping and Escape handling.
  const dialog = $("#image-dialog");
  const viewer = $("#lightbox-image");
  let activeImages = [];
  let currentImage = 0;
  let returnFocus = null;

  function showImage(index) {
    currentImage = (index + activeImages.length) % activeImages.length;
    const button = activeImages[currentImage];
    viewer.src = button.dataset.lightbox;
    viewer.alt = $("img", button)?.alt || button.dataset.caption || "Research figure";
    $("#lightbox-caption").textContent = button.dataset.caption || "";
    $("#lightbox-original").href = button.dataset.lightbox;
    $("#lightbox-counter").textContent = activeImages.length > 1 ? `${String(currentImage + 1).padStart(2, "0")} / ${String(activeImages.length).padStart(2, "0")}` : "REWARDFLOW · RESEARCH FIGURE";
    $(".lightbox-prev").disabled = activeImages.length < 2;
    $(".lightbox-next").disabled = activeImages.length < 2;
  }

  document.addEventListener("click", event => {
    const button = event.target.closest("[data-lightbox]");
    if (!button) return;
    returnFocus = button;
    const group = button.closest(".hero-showcase, .comparison-stage, .method-figure");
    activeImages = group ? $$("[data-lightbox]", group).filter(el => el.getClientRects().length > 0) : [button];
    showImage(activeImages.indexOf(button));
    dialog.showModal();
    document.body.classList.add("modal-open");
    $(".lightbox-close").focus();
  });
  $(".lightbox-close").addEventListener("click", () => dialog.close());
  $(".lightbox-prev").addEventListener("click", () => showImage(currentImage - 1));
  $(".lightbox-next").addEventListener("click", () => showImage(currentImage + 1));
  dialog.addEventListener("click", event => { if (event.target === dialog) dialog.close(); });
  dialog.addEventListener("keydown", event => {
    if (event.key === "ArrowRight") { event.preventDefault(); showImage(currentImage + 1); }
    if (event.key === "ArrowLeft") { event.preventDefault(); showImage(currentImage - 1); }
  });
  dialog.addEventListener("close", () => {
    document.body.classList.remove("modal-open");
    returnFocus?.focus({preventScroll:true});
  });

  function renderPrompt(key) {
    const prompt = data.prompts[key];
    const keys = Object.keys(data.prompts);
    $("#prompt-text").textContent = prompt.text;
    $("#prompt-counter").textContent = `${String(keys.indexOf(key) + 1).padStart(2,"0")} / 06`;
    $$("[data-prompt]").forEach(button => {
      const active = button.dataset.prompt === key;
      button.classList.toggle("active", active);
      button.setAttribute("aria-pressed", String(active));
    });
    ["flow", "reward"].forEach(method => {
      const fragment = document.createDocumentFragment();
      const name = method === "flow" ? "Flow-GRPO" : "RewardFlow";
      for (let index = 1; index <= 3; index++) {
        const button = document.createElement("button");
        button.className = "sample-button";
        button.type = "button";
        button.dataset.lightbox = `assets/images/${key}-${method}-${index}.jpg`;
        button.dataset.caption = `${name} · ${prompt.name} · Sample ${index}. Prompt: ${prompt.text}`;
        button.setAttribute("aria-label", `Enlarge ${name} sample ${index}: ${prompt.name}`);
        const img = document.createElement("img");
        img.src = button.dataset.lightbox;
        img.alt = `${prompt.name}, sample ${index} generated by ${name}`;
        img.width = 512;
        img.height = 512;
        img.loading = "lazy";
        const label = document.createElement("span");
        label.className = "sample-index";
        label.textContent = `0${index}`;
        button.append(img, label);
        fragment.append(button);
      }
      $(`#${method}-samples`).replaceChildren(fragment);
    });
  }
  $$("[data-prompt]").forEach(button => button.addEventListener("click", () => renderPrompt(button.dataset.prompt)));
  renderPrompt(Object.keys(data.prompts)[0]);

  let backbone = "sd35";
  function renderResults(announce = false) {
    const settingKey = $("#reward-setting").value;
    const setting = data.settings[settingKey];
    const rows = [{name:data.backbones[backbone], values:data.base[backbone]}, ...data.results[backbone][settingKey]];
    const maxima = data.metrics.map((_, i) => Math.max(...rows.map(row => row.values[i] ?? -Infinity)));
    const fragment = document.createDocumentFragment();
    rows.forEach(row => {
      const tr = document.createElement("tr");
      const ours = row.name === "RewardFlow";
      if (ours) tr.className = "highlight-row";
      const th = document.createElement("th");
      th.scope = "row";
      th.textContent = row.name;
      if (ours) {
        const tag = document.createElement("span");
        tag.className = "ours-tag";
        tag.textContent = "OURS";
        th.append(tag);
      }
      tr.append(th);
      row.values.forEach((value, index) => {
        const td = document.createElement("td");
        td.textContent = value === null ? "—" : value.toFixed(3);
        if (value === null) td.setAttribute("aria-label", "Not reported");
        if (value !== null && value === maxima[index]) td.className = "best";
        tr.append(td);
      });
      fragment.append(tr);
    });
    $("#benchmark-table tbody").replaceChildren(fragment);
    $$("#benchmark-table [data-metric]").forEach(th => {
      const trained = setting.trained.includes(th.dataset.metric);
      th.classList.toggle("training-metric", trained);
      th.setAttribute("aria-label", `${th.textContent}, higher is better, ${trained ? "training reward" : "evaluation metric"}`);
    });
    $("#results-description").textContent = setting.description;
    $("#benchmark-caption").textContent = `${data.backbones[backbone]} — ${setting.description}`;
    $("#result-source").textContent = `Source: ${setting.source} in the paper. Bold = column best${settingKey === "preference" ? ", including ties." : "."}${["hps","geneval","ocr"].includes(settingKey) ? " — = not reported. Base-model scores are provided as a reference." : ""}`;
    if (announce) $("#results-announcement").textContent = `Showing ${data.backbones[backbone]}. ${setting.description}. ${rows.length} methods.`;
  }
  $$("[data-backbone]").forEach(button => button.addEventListener("click", () => {
    backbone = button.dataset.backbone;
    $$("[data-backbone]").forEach(other => {
      const active = other === button;
      other.classList.toggle("active", active);
      other.setAttribute("aria-pressed", String(active));
    });
    renderResults(true);
  }));
  $("#reward-setting").addEventListener("change", () => renderResults(true));
  renderResults();

  const copyButton = $("#copy-citation");
  let copyReset;
  copyButton.addEventListener("click", async () => {
    const text = $("#bibtex").textContent.trim();
    const status = $(".copy-status");
    try {
      if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(text);
      } else {
        const textarea = document.createElement("textarea");
        textarea.value = text;
        textarea.style.cssText = "position:fixed;left:-9999px;top:0";
        document.body.append(textarea);
        textarea.select();
        const copied = document.execCommand("copy");
        textarea.remove();
        copyButton.focus({preventScroll:true});
        if (!copied) throw new Error("Clipboard unavailable");
      }
      $("span", copyButton).textContent = "Copied!";
      status.classList.remove("error");
      status.textContent = "Citation copied to clipboard.";
    } catch (_) {
      status.classList.add("error");
      status.textContent = "Select the citation, or download the .bib file.";
    }
    clearTimeout(copyReset);
    copyReset = setTimeout(() => { $("span", copyButton).textContent = "Copy"; status.textContent = ""; }, 5000);
  });

  const toggle = $(".menu-toggle");
  const nav = $("#main-nav");
  function closeMenu() {
    toggle.setAttribute("aria-expanded", "false");
    toggle.setAttribute("aria-label", "Open navigation");
    nav.classList.remove("open");
  }
  toggle.addEventListener("click", () => {
    const open = toggle.getAttribute("aria-expanded") !== "true";
    toggle.setAttribute("aria-expanded", String(open));
    toggle.setAttribute("aria-label", open ? "Close navigation" : "Open navigation");
    nav.classList.toggle("open", open);
  });
  $$("a", nav).forEach(a => a.addEventListener("click", closeMenu));
  document.addEventListener("keydown", event => { if (event.key === "Escape") closeMenu(); });

  const navLinks = $$("a", nav);
  const sections = navLinks.map(a => $(a.getAttribute("href")));
  let scrollPending = false;
  function updateReading() {
    const max = document.documentElement.scrollHeight - window.innerHeight;
    $(".reading-progress").style.width = `${max > 0 ? window.scrollY / max * 100 : 0}%`;
    let current = null;
    sections.forEach(section => { if (section.getBoundingClientRect().top <= 180) current = section.id; });
    navLinks.forEach(link => {
      const active = link.hash === `#${current}`;
      link.classList.toggle("active", active);
      if (active) link.setAttribute("aria-current", "location");
      else link.removeAttribute("aria-current");
    });
    scrollPending = false;
  }
  window.addEventListener("scroll", () => {
    if (!scrollPending) { scrollPending = true; requestAnimationFrame(updateReading); }
  }, {passive:true});
  window.addEventListener("resize", () => { if (window.innerWidth > 620) closeMenu(); updateReading(); });
  updateReading();
  window.rewardFlowReady = true;
})();
